static int vector_length(const native_vec *vector, size_t minimum,
                         size_t maximum, size_t *length_out, char *error,
                         size_t error_capacity,
                         const char *invalid_detail) {
  int64_t length;

  if (vector == NULL) {
    copy_error(error, error_capacity, invalid_detail);
    return BEAGLE_STORE_SERVER_FATAL;
  }
  length = native_vec_length(vector);
  if (length < INT64_C(0) || (uint64_t)length > (uint64_t)SIZE_MAX ||
      (size_t)length < minimum || (size_t)length > maximum) {
    copy_error(error, error_capacity, invalid_detail);
    return BEAGLE_STORE_SERVER_FATAL;
  }
  *length_out = (size_t)length;
  return BEAGLE_STORE_SERVER_OK;
}

static int write_bytes(int fd, const uint8_t *bytes, size_t length,
                       char *error, size_t error_capacity) {
  size_t position = 0u;

  while (position < length) {
    ssize_t count = write(fd, bytes + position, length - position);

    if (count > 0) {
      position += (size_t)count;
    } else if (count < 0 && errno == EINTR) {
      continue;
    } else if (count < 0 && (errno == EPIPE || errno == ECONNRESET)) {
      return BEAGLE_STORE_SERVER_PEER_CLOSED;
    } else {
      copy_error(error, error_capacity,
                 "cannot write the generated response packet");
      return BEAGLE_STORE_SERVER_CLIENT_ERROR;
    }
  }
  return BEAGLE_STORE_SERVER_OK;
}

static int append_log_vector(store_server_store *store,
                             const native_vec *vector, bool sync_after_write,
                             char *error, size_t error_capacity) {
  uint8_t chunk[BEAGLE_STORE_SERVER_IO_CHUNK_BYTES];
  size_t length;
  size_t offset = 0u;
  int status = vector_length(
      vector, 0u, SIZE_MAX, &length, error, error_capacity,
      "generated Store transaction log append is not byte-valued");

  if (status != BEAGLE_STORE_SERVER_OK || length == 0u) {
    return status;
  }
  while (offset < length) {
    size_t count = length - offset;
    size_t index;

    if (count > sizeof(chunk)) {
      count = sizeof(chunk);
    }
    for (index = 0u; index < count; index += 1u) {
      const int64_t *value = native_vec_at(
          vector, (int64_t)(offset + index), INT64_C(8));

      if (*value < INT64_C(0) || *value > INT64_C(255)) {
        copy_error(error, error_capacity,
                   "generated Store transaction log append is not byte-valued");
        return BEAGLE_STORE_SERVER_FATAL;
      }
      chunk[index] = (uint8_t)*value;
    }
    status = store->host.storage_append(store->host.context, chunk, count,
                                        error, error_capacity);
    if (status != BEAGLE_STORE_SERVER_OK) {
      return status;
    }
    offset += count;
  }
  if (sync_after_write) {
    status = store->host.storage_sync(store->host.context, error,
                                      error_capacity);
    if (status != BEAGLE_STORE_SERVER_OK) {
      return status;
    }
  }
  return BEAGLE_STORE_SERVER_OK;
}

static int repair_log_tail(store_server_store *store,
                           size_t original_length, int64_t valid_length,
                           char *error, size_t error_capacity) {
  if (valid_length < INT64_C(0) ||
      (uint64_t)valid_length > (uint64_t)original_length) {
    copy_error(
        error, error_capacity,
        "generated Store transaction log recovery returned an invalid prefix");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  if ((size_t)valid_length == original_length) {
    return BEAGLE_STORE_SERVER_OK;
  }
  return store->host.storage_truncate(
      store->host.context, (uint64_t)valid_length, error, error_capacity);
}

static uint32_t packet_body_length(const uint8_t *header) {
  return (uint32_t)header[STORE_RPC_PACKET_BODY_LENGTH_OFFSET] |
         ((uint32_t)header[STORE_RPC_PACKET_BODY_LENGTH_OFFSET + 1u]
          << 8u) |
         ((uint32_t)header[STORE_RPC_PACKET_BODY_LENGTH_OFFSET + 2u]
          << 16u) |
         ((uint32_t)header[STORE_RPC_PACKET_BODY_LENGTH_OFFSET + 3u]
          << 24u);
}

static int read_packet(int fd, uint8_t **packet_out, size_t *length_out,
                      char *error, size_t error_capacity) {
  uint8_t header[STORE_RPC_PACKET_HEADER_BYTES];
  uint8_t *packet;
  uint32_t body_length;
  size_t packet_length;
  int status = read_exact(
      fd, header, sizeof(header), true, BEAGLE_STORE_SERVER_CLIENT_ERROR,
      "generated request packet ended inside its header",
      "cannot read the generated request packet header", error,
      error_capacity);

  if (status != BEAGLE_STORE_SERVER_OK) {
    return status;
  }
  body_length = packet_body_length(header);
  if (body_length > STORE_RPC_PACKET_MAX_BODY_BYTES) {
    copy_error(error, error_capacity,
               "generated request packet exceeds the body limit");
    return BEAGLE_STORE_SERVER_CLIENT_ERROR;
  }
  packet_length = sizeof(header) + (size_t)body_length;
  packet = malloc(packet_length);
  if (packet == NULL) {
    copy_error(error, error_capacity,
               "cannot allocate the generated request packet");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  memcpy(packet, header, sizeof(header));
  status = read_exact(fd, packet + sizeof(header), (size_t)body_length, false,
                      BEAGLE_STORE_SERVER_CLIENT_ERROR,
                      "generated request packet ended inside its body",
                      "cannot read the generated request packet body", error,
                      error_capacity);
  if (status != BEAGLE_STORE_SERVER_OK) {
    free(packet);
    return status;
  }
  *packet_out = packet;
  *length_out = packet_length;
  return BEAGLE_STORE_SERVER_OK;
}

static int read_whole_object(const store_server_host_v1 *host, void *context,
                             uint8_t **bytes_out, size_t *length_out,
                             const char *oversize_detail,
                             const char *allocate_detail, char *error,
                             size_t error_capacity) {
  uint64_t host_length;
  size_t length;
  uint8_t *bytes = NULL;
  int status;

  *bytes_out = NULL;
  *length_out = 0u;
  status = host->storage_size(context, &host_length, error, error_capacity);
  if (status != BEAGLE_STORE_SERVER_OK) {
    return status;
  }
  if (host_length > (uint64_t)SIZE_MAX || host_length > (uint64_t)INT64_MAX) {
    copy_error(error, error_capacity, oversize_detail);
    return BEAGLE_STORE_SERVER_FATAL;
  }
  length = (size_t)host_length;
  if (length != 0u) {
    bytes = malloc(length);
    if (bytes == NULL) {
      copy_error(error, error_capacity, allocate_detail);
      return BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
    }
  }
  status = host->storage_read(context, UINT64_C(0), bytes, length, error,
                              error_capacity);
  if (status != BEAGLE_STORE_SERVER_OK) {
    free(bytes);
    return status;
  }
  *bytes_out = bytes;
  *length_out = length;
  return BEAGLE_STORE_SERVER_OK;
}

/* Silent in the host-import regime: that guest holds no stderr capability, so
   its embedder reads the route from the image object instead. */
static void report_snapshot_line(uint64_t text) {
#ifdef BEAGLE_STORE_WASM_HOST_IMPORTS
  (void)text;
#else
  uint64_t length = native_text_length(text);
  const uint8_t *bytes = native_text_bytes(text);

  if (length == UINT64_C(0) || bytes == NULL ||
      length > (uint64_t)BEAGLE_STORE_SERVER_ERROR_CAPACITY) {
    return;
  }
  (void)!write(2, bytes, (size_t)length);
  (void)!write(2, "\n", (size_t)1u);
#endif
}

/* Only a host that named a budget gets this line, so a default boot's stderr
   is byte-identical to what it was before limits became derivable. */
static void report_derived_limits(const store_server_limits *limits) {
#ifdef BEAGLE_STORE_WASM_HOST_IMPORTS
  (void)limits;
#else
  char line[160];
  int length = snprintf(
      line, sizeof(line),
      "store: engine memory limits derived from the host budget: "
      "arena-growth=%llu compact-increment=%llu compact-generations=%llu\n",
      (unsigned long long)limits->arena_growth_bytes,
      (unsigned long long)limits->compact_increment_bytes,
      (unsigned long long)limits->compact_generations);

  if (length > 0) {
    (void)!write(2, line,
                 (size_t)length < sizeof(line) ? (size_t)length
                                               : sizeof(line) - 1u);
  }
#endif
}

static int write_snapshot_vector(store_server_store *store,
                                 const native_vec *vector, char *error,
                                 size_t error_capacity) {
  uint8_t chunk[BEAGLE_STORE_SERVER_IO_CHUNK_BYTES];
  size_t length;
  size_t offset = 0u;
  int status = vector_length(vector, 0u, SIZE_MAX, &length, error,
                             error_capacity,
                             "generated snapshot image is not byte-valued");

  if (status != BEAGLE_STORE_SERVER_OK || length == 0u) {
    return status;
  }
  if (store->host.snapshot_context == NULL) {
    copy_error(error, error_capacity,
               "this host serves no snapshot storage object");
    return BEAGLE_STORE_SERVER_HOST_ERROR;
  }
  status = store->host.storage_truncate(store->host.snapshot_context,
                                        UINT64_C(0), error, error_capacity);
  if (status != BEAGLE_STORE_SERVER_OK) {
    return status;
  }
  while (offset < length) {
    size_t count = length - offset;
    size_t index;

    if (count > sizeof(chunk)) {
      count = sizeof(chunk);
    }
    for (index = 0u; index < count; index += 1u) {
      const int64_t *value = native_vec_at(
          vector, (int64_t)(offset + index), INT64_C(8));

      if (*value < INT64_C(0) || *value > INT64_C(255)) {
        copy_error(error, error_capacity,
                   "generated snapshot image is not byte-valued");
        return BEAGLE_STORE_SERVER_FATAL;
      }
      chunk[index] = (uint8_t)*value;
    }
    status = store->host.storage_append(store->host.snapshot_context, chunk,
                                        count, error, error_capacity);
    if (status != BEAGLE_STORE_SERVER_OK) {
      return status;
    }
    offset += count;
  }
  return store->host.storage_sync(store->host.snapshot_context, error,
                                  error_capacity);
}

static int boot_generation_from_log(
    store_server_store *store, const char *canonical_log_path,
    const char *space_id, bool report_snapshot,
    generated_store_generation **generation_out, size_t *log_length_out,
    char *error, size_t error_capacity) {
  generated_owner *owner = NULL;
  generated_store_generation *generation = NULL;
  uint8_t *log_bytes = NULL;
  uint8_t *snapshot_bytes = NULL;
  native_byte_source *borrowed = NULL;
  native_byte_source *borrowed_snapshot = NULL;
  size_t log_length = 0u;
  size_t snapshot_length = 0u;
  store_server_store_boot_arg_0 generated_log_path;
  store_server_store_boot_arg_1 generated_space_id;
  store_server_store_boot_return result;
  int status;

  *generation_out = NULL;
  status = read_whole_object(
      &store->host, store->host.context, &log_bytes, &log_length,
      "canonical Store transaction log exceeds the native address range",
      "cannot allocate the canonical Store transaction log input", error,
      error_capacity);
  if (status != BEAGLE_STORE_SERVER_OK) {
    return status;
  }
  if (store->host.snapshot_context != NULL) {
    status = read_whole_object(
        &store->host, store->host.snapshot_context, &snapshot_bytes,
        &snapshot_length, "snapshot image exceeds the native address range",
        "cannot allocate the snapshot image input", error, error_capacity);
    if (status != BEAGLE_STORE_SERVER_OK) {
      free(log_bytes);
      return status;
    }
  }
  owner = owner_create(store->limits.arena_growth_bytes, error,
                       error_capacity);
  if (owner == NULL) {
    free(log_bytes);
    free(snapshot_bytes);
    return BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
  }
  if (!borrow_bytes(&owner->arena, log_bytes, log_length, &borrowed, error,
                    error_capacity) ||
      !borrow_bytes(&owner->arena, snapshot_bytes, snapshot_length,
                    &borrowed_snapshot, error, error_capacity)) {
    status = BEAGLE_STORE_SERVER_FATAL;
    goto cleanup;
  }
  generated_log_path = native_text_from_c(&owner->arena, canonical_log_path);
  generated_space_id =
      native_text_from_c(&owner->arena, space_id != NULL ? space_id : "");
  result = BEAGLE_STORE_SERVER_CALL_STORE_BOOT(
      &owner->arena, &owner->capability, generated_log_path,
      generated_space_id, borrowed, borrowed_snapshot);
  status = generated_status((int64_t)result.field_0, error, error_capacity,
                            "generated store boot failed");
  if (status == BEAGLE_STORE_SERVER_OK) {
    if (report_snapshot) {
      report_snapshot_line(result.field_5);
    }
    generation = generation_create(owner, NULL, result, error, error_capacity);
    if (generation == NULL) {
      status = BEAGLE_STORE_SERVER_FATAL;
    }
  }

cleanup:
  free(log_bytes);
  free(snapshot_bytes);
  owner_release(owner);
  if (status != BEAGLE_STORE_SERVER_OK) {
    if (generation != NULL) {
      generation_release(generation);
    }
    return status;
  }
  *generation_out = generation;
  *log_length_out = log_length;
  return BEAGLE_STORE_SERVER_OK;
}

static bool store_needs_compaction(const store_server_store *store) {
  const generated_store_generation *current = store->current;

  return current->chain_generations - store->compaction_base_generations >=
             store->limits.compact_generations ||
         current->chain_reserved_bytes - store->compaction_base_bytes >=
             store->limits.compact_increment_bytes;
}

static int compact_store(store_server_store *store, char *error,
                         size_t error_capacity) {
  generated_store_generation *replacement = NULL;
  generated_store_generation *previous;
  size_t log_length;
  size_t append_length;
  int status = boot_generation_from_log(
      store, store->canonical_log_path, store->space_id, false, &replacement,
      &log_length, error, error_capacity);

  if (status != BEAGLE_STORE_SERVER_OK) {
    return status;
  }
  status = vector_length(
      replacement->result.field_4, 0u, SIZE_MAX, &append_length, error,
      error_capacity,
      "generated compacted Store transaction log append is invalid");
  if (status != BEAGLE_STORE_SERVER_OK || append_length != 0u ||
      replacement->result.field_3 < INT64_C(0) ||
      (uint64_t)replacement->result.field_3 != (uint64_t)log_length) {
    generation_release(replacement);
    copy_error(
        error, error_capacity,
        "generated compaction did not consume the canonical Store transaction log");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  previous = store->current;
  store->current = replacement;
  store->compaction_base_bytes = replacement->chain_reserved_bytes;
  store->compaction_base_generations = replacement->chain_generations;
  generation_release(previous);
  return BEAGLE_STORE_SERVER_OK;
}

/* Compaction is what returns a generation chain's arenas to the allocator, and
   until now only a write could reach it: an idle server parked forever on
   whichever peak its last write left. The chain carries its own answer to
   "would this repeat work" -- a compacted store has exactly one generation and
   sets its base to it, so any excess over the base is unprojected writes. */
int store_server_store_compact_idle(store_server_store *store,
                                   int *compacted_out, char *error,
                                   size_t error_capacity) {
  int status;

  clear_error(error, error_capacity);
  if (compacted_out != NULL) {
    *compacted_out = 0;
  }
  if (store == NULL) {
    copy_error(error, error_capacity,
               "generated idle compaction requires an owned store");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  if (store->poisoned) {
    copy_error(
        error, error_capacity,
        "canonical Store transaction log is poisoned after a durability failure");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  if (store->current->chain_generations <=
      store->compaction_base_generations) {
    return BEAGLE_STORE_SERVER_OK;
  }
  status = compact_store(store, error, error_capacity);
  if (status == BEAGLE_STORE_SERVER_OK && compacted_out != NULL) {
    *compacted_out = 1;
  }
  return status;
}

uint32_t store_server_generated_abi(void) {
  generated_owner *owner =
      owner_create(BEAGLE_STORE_SERVER_DEFAULT_ARENA_GROWTH_BYTES, NULL, 0u);
  store_server_generated_abi_return result;

  if (owner == NULL) {
    return UINT32_C(0);
  }
  result = BEAGLE_STORE_SERVER_CALL_GENERATED_ABI(&owner->arena,
                                              &owner->capability);
  owner_release(owner);
  if ((int64_t)result < INT64_C(0) ||
      (int64_t)result > (int64_t)UINT32_MAX) {
    return UINT32_C(0);
  }
  return (uint32_t)result;
}

int store_server_store_boot_with_host(const char *canonical_log_path,
                                     const char *space_id,
                                     const store_server_host_v1 *host,
                                     store_server_store **store_out,
                                     char *error, size_t error_capacity) {
  store_server_store *store = NULL;
  generated_store_generation *generation = NULL;
  size_t log_length;
  size_t append_length;
  int status;

  clear_error(error, error_capacity);
  if (store_out == NULL || canonical_log_path == NULL || !valid_host(host)) {
    copy_error(error, error_capacity,
               "generated store boot requires a log label, host, and output owner");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  *store_out = NULL;
  store = malloc(sizeof(*store));
  if (store == NULL) {
    copy_error(error, error_capacity,
               "cannot allocate the generated store wrapper");
    return BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
  }
  memset(store, 0, sizeof(*store));
  store->canonical_log_path =
      duplicate_string(canonical_log_path, error, error_capacity);
  store->space_id = duplicate_string(space_id != NULL ? space_id : "", error,
                                     error_capacity);
  if (store->canonical_log_path == NULL || store->space_id == NULL) {
    status = BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
    goto boot_failed;
  }
  store->host = *host;
  store->limits = derive_limits(host->memory_budget_bytes);
  store->poisoned = false;
  if (host->memory_budget_bytes != UINT64_C(0)) {
    report_derived_limits(&store->limits);
  }
  status = boot_generation_from_log(
      store, store->canonical_log_path, store->space_id, true, &generation,
      &log_length, error, error_capacity);
  if (status == BEAGLE_STORE_SERVER_OK) {
    store->current = generation;
    status = repair_log_tail(store, log_length,
                             (int64_t)generation->result.field_3, error,
                             error_capacity);
  }
  if (status == BEAGLE_STORE_SERVER_OK) {
    status = vector_length(generation->result.field_4, 0u, SIZE_MAX,
                           &append_length, error, error_capacity,
                           "generated boot append is not byte-valued");
  }
  if (status == BEAGLE_STORE_SERVER_OK && append_length != 0u) {
    status = append_log_vector(store, generation->result.field_4, false,
                               error, error_capacity);
  }
  if (status == BEAGLE_STORE_SERVER_OK) {
    status = store->host.storage_sync(store->host.context, error,
                                      error_capacity);
  }
  if (status != BEAGLE_STORE_SERVER_OK) {
    goto boot_failed;
  }
  store->compaction_base_bytes = generation->chain_reserved_bytes;
  store->compaction_base_generations = generation->chain_generations;
  *store_out = store;
  return BEAGLE_STORE_SERVER_OK;

boot_failed:
  if (generation != NULL) {
    generation_release(generation);
  }
  free(store->space_id);
  free(store->canonical_log_path);
  free(store);
  return status;
}

