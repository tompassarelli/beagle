/* snapshot_context is allowed to be NULL: a host may serve no snapshot object,
   and a checkpoint then reports that instead of writing one. */
static bool valid_host(const store_server_host_v1 *host) {
  return host != NULL && host->abi_version == BEAGLE_STORE_SERVER_HOST_ABI &&
         host->struct_size >= (uint32_t)sizeof(*host) &&
         host->clock_milliseconds != NULL && host->storage_size != NULL &&
         host->storage_read != NULL && host->storage_truncate != NULL &&
         host->storage_append != NULL && host->storage_sync != NULL &&
         host->storage_close != NULL;
}

static int read_exact(int fd, uint8_t *destination, size_t length,
                      bool clean_eof_is_peer_closed,
                      int failure_status,
                      const char *truncated_detail, const char *read_detail,
                      char *error, size_t error_capacity) {
  size_t position = 0u;

  while (position < length) {
    ssize_t count = read(fd, destination + position, length - position);

    if (count > 0) {
      position += (size_t)count;
      continue;
    }
    if (count == 0) {
      if (position == 0u && clean_eof_is_peer_closed) {
        return BEAGLE_STORE_SERVER_PEER_CLOSED;
      }
      copy_error(error, error_capacity, truncated_detail);
      return failure_status;
    }
    if (errno == EINTR) {
      continue;
    }
    copy_error(error, error_capacity, read_detail);
    return failure_status;
  }
  return BEAGLE_STORE_SERVER_OK;
}

