static char *snapshot_path_of(const char *canonical_log_path, char *error,
                              size_t error_capacity) {
  size_t length = strlen(canonical_log_path);
  size_t suffix = strlen(BEAGLE_STORE_SERVER_SNAPSHOT_SUFFIX);
  char *path;

  if (length > SIZE_MAX - suffix - 1u) {
    copy_error(error, error_capacity, "snapshot image path overflowed");
    return NULL;
  }
  path = malloc(length + suffix + 1u);
  if (path == NULL) {
    copy_error(error, error_capacity, "cannot allocate the snapshot path");
    return NULL;
  }
  memcpy(path, canonical_log_path, length);
  memcpy(path + length, BEAGLE_STORE_SERVER_SNAPSHOT_SUFFIX, suffix + 1u);
  return path;
}

