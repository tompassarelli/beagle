/* The generated encoder reads the dispatch result in place, so this must run
   while the arenas that result points into are still live: inside dispatch,
   before the request owner or base generation can be released. */
static int encode_response_packet(
    const store_server_store_dispatch_return *result, uint8_t **bytes_out,
    size_t *length_out, char *error, size_t error_capacity) {
  generated_owner *owner;
  store_server_codec_write_response_return generated_result;
  uint8_t *bytes;
  size_t length;
  size_t index;
  int status;

  *bytes_out = NULL;
  *length_out = 0u;
  owner = owner_create(BEAGLE_STORE_SERVER_DEFAULT_ARENA_GROWTH_BYTES, error,
                       error_capacity);
  if (owner == NULL) {
    return BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
  }
  generated_result = BEAGLE_STORE_SERVER_CALL_CODEC_WRITE_RESPONSE(
      &owner->arena, &owner->capability, *result);
  status = generated_status((int64_t)generated_result.field_0, error,
                            error_capacity,
                            "generated response encode failed");
  if (status == BEAGLE_STORE_SERVER_OK) {
    status = vector_length(
        generated_result.field_1, STORE_RPC_PACKET_HEADER_BYTES,
        STORE_RPC_PACKET_MAX_BYTES, &length, error, error_capacity,
        "generated response packet has an invalid byte representation");
  }
  bytes = NULL;
  if (status == BEAGLE_STORE_SERVER_OK) {
    bytes = malloc(length);
    if (bytes == NULL) {
      copy_error(error, error_capacity,
                 "cannot allocate the encoded response packet");
      status = BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
    }
  }
  for (index = 0u; status == BEAGLE_STORE_SERVER_OK && index < length; index += 1u) {
    const int64_t *value = native_vec_at(generated_result.field_1,
                                         (int64_t)index, INT64_C(8));

    if (*value < INT64_C(0) || *value > INT64_C(255)) {
      copy_error(error, error_capacity,
                 "generated response packet has an invalid byte representation");
      status = BEAGLE_STORE_SERVER_FATAL;
    } else {
      bytes[index] = (uint8_t)*value;
    }
  }
  owner_release(owner);
  if (status != BEAGLE_STORE_SERVER_OK) {
    free(bytes);
    return status;
  }
  *bytes_out = bytes;
  *length_out = length;
  return BEAGLE_STORE_SERVER_OK;
}

int store_server_store_dispatch(store_server_store *store,
                                   const store_server_request *request,
                                   store_server_response **response_out,
                                   char *error, size_t error_capacity) {
  store_server_response *response;
  generated_store_generation *base_generation;
  generated_store_generation *next_generation = NULL;
  store_server_store_dispatch_return result;
  store_server_store_dispatch_arg_2 now_milliseconds;
  int64_t clock_milliseconds;
  uint8_t *bytes = NULL;
  size_t length = 0u;
  size_t append_length;
  int status;

  clear_error(error, error_capacity);
  if (store == NULL || request == NULL || response_out == NULL) {
    copy_error(error, error_capacity,
               "generated dispatch requires owned input and output values");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  *response_out = NULL;
  if (store->poisoned) {
    copy_error(
        error, error_capacity,
        "canonical Store transaction log is poisoned after a durability failure");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  if (store_needs_compaction(store)) {
    status = compact_store(store, error, error_capacity);
    if (status != BEAGLE_STORE_SERVER_OK) {
      return status;
    }
  }
  status = store->host.clock_milliseconds(
      store->host.context, &clock_milliseconds, error, error_capacity);
  if (status != BEAGLE_STORE_SERVER_OK) {
    return status;
  }
  now_milliseconds =
      (store_server_store_dispatch_arg_2)clock_milliseconds;
  response = malloc(sizeof(*response));
  if (response == NULL) {
    copy_error(error, error_capacity,
               "cannot allocate the generated response wrapper");
    return BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
  }
  /* The base generation and the request owner stay live for the whole call:
     the store holds its own reference to the base (directly, or through the
     replacement generation's parent chain after the swap below), and the
     caller owns the request. Only a state change takes new references, inside
     generation_create. */
  base_generation = store->current;
  result = BEAGLE_STORE_SERVER_CALL_STORE_DISPATCH(
      &request->owner->arena, &request->owner->capability,
      base_generation->result, request->result, now_milliseconds);
  status = generated_status((int64_t)result.field_0, error,
                            error_capacity,
                            "generated store dispatch failed");
  if (status == BEAGLE_STORE_SERVER_OK) {
    status = vector_length(result.field_3, 0u, SIZE_MAX,
                           &append_length, error, error_capacity,
                           "generated dispatch append is not byte-valued");
  }
  if (status == BEAGLE_STORE_SERVER_OK && append_length != 0u &&
      !result.field_5) {
    copy_error(error, error_capacity,
               "generated dispatch appended without changing state");
    status = BEAGLE_STORE_SERVER_FATAL;
  }
  if (status == BEAGLE_STORE_SERVER_OK && result.field_5) {
    next_generation = generation_create(
        request->owner, base_generation, result.field_4, error,
        error_capacity);
    if (next_generation == NULL) {
      status = BEAGLE_STORE_SERVER_FATAL;
    }
  }
  if (status == BEAGLE_STORE_SERVER_OK && append_length != 0u) {
    status = append_log_vector(store, result.field_3, true, error,
                               error_capacity);
    if (status != BEAGLE_STORE_SERVER_OK) {
      store->poisoned = true;
    }
  }
  if (status == BEAGLE_STORE_SERVER_OK && next_generation != NULL) {
    generated_store_generation *previous = store->current;

    store->current = next_generation;
    next_generation = NULL;
    generation_release(previous);
  }
  /* The image is a separate storage object; a failed image write never
     poisons the Store transaction log, which stays the authoritative
     history. */
  if (status == BEAGLE_STORE_SERVER_OK) {
    status = write_snapshot_vector(store, result.field_6, error,
                                   error_capacity);
  }
  if (status == BEAGLE_STORE_SERVER_OK) {
    status = encode_response_packet(&result, &bytes, &length, error,
                                    error_capacity);
  }
  (void)BEAGLE_STORE_SERVER_CALL_CODEC_RELEASE_RESPONSE(
      &request->owner->arena, &request->owner->capability, result);
  if (status != BEAGLE_STORE_SERVER_OK) {
    if (next_generation != NULL) {
      generation_release(next_generation);
    }
    free(response);
    return status;
  }
  response->bytes = bytes;
  response->length = length;
  *response_out = response;
  return BEAGLE_STORE_SERVER_OK;
}

int store_server_compile_query(
    store_server_store *store, const store_server_compile_key *key,
    store_server_compile_value *value,
    store_server_compile_query_result *result, char *error,
    size_t error_capacity) {
  generated_owner *owner = NULL;
  store_server_compile_query_return generated_result;
  uint64_t source;
  uint64_t compiler;
  uint64_t profile;
  native_vec *targets;
  uint64_t rules;
  uint64_t schema;
  uint64_t expected;
  int status;

  clear_error(error, error_capacity);
  if (value != NULL) {
    *value = (store_server_compile_value){0};
  }
  if (result != NULL) {
    *result = (store_server_compile_query_result){
        .status = BEAGLE_STORE_SERVER_FATAL,
        .found = false,
        .outcome = BEAGLE_STORE_SERVER_COMPILE_COLD,
    };
  }
  if (store == NULL || key == NULL || value == NULL || result == NULL) {
    copy_error(error, error_capacity,
               "generated compile query requires a store, key, value, and result owner");
    if (result != NULL) {
      result->status = BEAGLE_STORE_SERVER_CLIENT_ERROR;
    }
    return BEAGLE_STORE_SERVER_CLIENT_ERROR;
  }
  if (store->poisoned) {
    copy_error(
        error, error_capacity,
        "canonical Store transaction log is poisoned after a durability failure");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  if (store_needs_compaction(store)) {
    status = compact_store(store, error, error_capacity);
    if (status != BEAGLE_STORE_SERVER_OK) {
      result->status = status;
      return status;
    }
  }
  owner = owner_create(store->limits.arena_growth_bytes, error,
                       error_capacity);
  if (owner == NULL) {
    result->status = BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
    return BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
  }
  status = compile_arguments(owner, key, &source, &compiler, &profile,
                             &targets, &rules, &schema, &expected, error,
                             error_capacity);
  if (status != BEAGLE_STORE_SERVER_OK) {
    owner_release(owner);
    result->status = status;
    return status;
  }
  generated_result = BEAGLE_STORE_SERVER_CALL_COMPILE_QUERY(
      &owner->arena, &owner->capability, store->current->result,
      (store_server_compile_query_arg_1)source,
      (store_server_compile_query_arg_2)compiler,
      (store_server_compile_query_arg_3)profile,
      (store_server_compile_query_arg_4)targets,
      (store_server_compile_query_arg_5)rules,
      (store_server_compile_query_arg_6)schema,
      (store_server_compile_query_arg_7)expected);
  status = generated_status((int64_t)generated_result.field_0, error,
                            error_capacity,
                            "generated compile query failed");
  if (status != BEAGLE_STORE_SERVER_OK) {
    copy_generated_error(
        (int64_t)generated_result.field_3.tag,
        generated_result.field_3.tag == INT64_C(0)
            ? (uint64_t)generated_result.field_3.payload.variant_0
            : UINT64_C(0),
        error, error_capacity, "generated compile query failed");
  } else if (generated_result.field_1) {
    if ((int64_t)generated_result.field_2.tag != INT64_C(0) ||
        generated_result.field_2.payload.variant_0 == NULL) {
      copy_error(error, error_capacity,
                 "generated compile query found no stored value");
      status = BEAGLE_STORE_SERVER_FATAL;
    } else {
      status = copy_compile_value(
          generated_result.field_2.payload.variant_0, value, error,
          error_capacity);
    }
  } else if ((int64_t)generated_result.field_2.tag != INT64_C(1)) {
    copy_error(error, error_capacity,
               "generated cold compile query returned a stored value");
    status = BEAGLE_STORE_SERVER_FATAL;
  }
  if (status == BEAGLE_STORE_SERVER_OK) {
    result->status = BEAGLE_STORE_SERVER_OK;
    result->found = generated_result.field_1;
    result->outcome = generated_result.field_1
                          ? BEAGLE_STORE_SERVER_COMPILE_FOUND
                          : BEAGLE_STORE_SERVER_COMPILE_COLD;
  }
  owner_release(owner);
  if (status != BEAGLE_STORE_SERVER_OK) {
    store_server_compile_value_release(value);
    result->status = status;
  }
  return status;
}

int store_server_compile_append(
    store_server_store *store, const store_server_compile_key *key,
    const store_server_compile_value *value,
    store_server_compile_query_result *result, char *error,
    size_t error_capacity) {
  generated_owner *owner = NULL;
  generated_store_generation *next_generation = NULL;
  generated_store_generation *base_generation;
  store_server_compile_append_return generated_result;
  uint64_t source;
  uint64_t compiler;
  uint64_t profile;
  native_vec *targets;
  uint64_t rules;
  uint64_t schema;
  uint64_t expected;
  uint64_t target;
  uint64_t materializer;
  uint64_t value_status;
  uint64_t claimed_id;
  uint64_t payload;
  size_t append_length;
  int status;

  clear_error(error, error_capacity);
  if (result != NULL) {
    *result = (store_server_compile_query_result){
        .status = BEAGLE_STORE_SERVER_FATAL,
        .found = false,
        .outcome = BEAGLE_STORE_SERVER_COMPILE_RETAINED,
    };
  }
  if (store == NULL || key == NULL || value == NULL || result == NULL ||
      !valid_compile_slice(value->target) ||
      !valid_compile_slice(value->materializer) ||
      !valid_compile_slice(value->status) ||
      !valid_compile_slice(value->claimed_id) ||
      !valid_utf8(value->payload.data, value->payload.length)) {
    copy_error(error, error_capacity,
               "generated compile append requires a store, key, UTF-8 value, and result owner");
    if (result != NULL) {
      result->status = BEAGLE_STORE_SERVER_CLIENT_ERROR;
    }
    return BEAGLE_STORE_SERVER_CLIENT_ERROR;
  }
  if (store->poisoned) {
    copy_error(
        error, error_capacity,
        "canonical Store transaction log is poisoned after a durability failure");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  if (store_needs_compaction(store)) {
    status = compact_store(store, error, error_capacity);
    if (status != BEAGLE_STORE_SERVER_OK) {
      result->status = status;
      return status;
    }
  }
  owner = owner_create(store->limits.arena_growth_bytes, error,
                       error_capacity);
  if (owner == NULL) {
    result->status = BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
    return BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
  }
  status = compile_arguments(owner, key, &source, &compiler, &profile,
                             &targets, &rules, &schema, &expected, error,
                             error_capacity);
  if (status != BEAGLE_STORE_SERVER_OK) {
    result->status = status;
    goto cleanup;
  }
  target = native_text_from_slice(&owner->arena, value->target);
  materializer = native_text_from_slice(&owner->arena, value->materializer);
  value_status = native_text_from_slice(&owner->arena, value->status);
  claimed_id = native_text_from_slice(&owner->arena, value->claimed_id);
  payload = native_text_from_slice(
      &owner->arena,
      (store_server_compile_slice){value->payload.data,
                                   value->payload.length});
  base_generation = store->current;
  generated_result = BEAGLE_STORE_SERVER_CALL_COMPILE_APPEND(
      &owner->arena, &owner->capability, base_generation->result,
      (store_server_compile_append_arg_1)source,
      (store_server_compile_append_arg_2)compiler,
      (store_server_compile_append_arg_3)profile,
      (store_server_compile_append_arg_4)targets,
      (store_server_compile_append_arg_5)rules,
      (store_server_compile_append_arg_6)schema,
      (store_server_compile_append_arg_7)expected,
      (store_server_compile_append_arg_8)target,
      (store_server_compile_append_arg_9)materializer,
      (store_server_compile_append_arg_10)value_status,
      (store_server_compile_append_arg_11)claimed_id,
      (store_server_compile_append_arg_12)payload);
  status = generated_status((int64_t)generated_result.field_0, error,
                            error_capacity,
                            "generated compile append failed");
  if (status != BEAGLE_STORE_SERVER_OK) {
    copy_generated_error(
        (int64_t)generated_result.field_3.tag,
        generated_result.field_3.tag == INT64_C(0)
            ? (uint64_t)generated_result.field_3.payload.variant_0
            : UINT64_C(0),
        error, error_capacity, "generated compile append failed");
    goto cleanup;
  }
  if ((int64_t)generated_result.field_2.tag != INT64_C(0) ||
      generated_result.field_2.payload.variant_0 == NULL) {
    copy_error(error, error_capacity,
               "generated compile append returned no stored value");
    status = BEAGLE_STORE_SERVER_FATAL;
    goto cleanup;
  }
  status = vector_length(
      generated_result.field_4, 0u, SIZE_MAX, &append_length, error,
      error_capacity,
      "generated compile append log bytes are not byte-valued");
  if (status != BEAGLE_STORE_SERVER_OK) {
    goto cleanup;
  }
  if (((int64_t)generated_result.field_1 == INT64_C(0) &&
       (!generated_result.field_6 || append_length == 0u)) ||
      ((int64_t)generated_result.field_1 == INT64_C(1) &&
       (generated_result.field_6 || append_length != 0u)) ||
      ((int64_t)generated_result.field_1 != INT64_C(0) &&
       (int64_t)generated_result.field_1 != INT64_C(1))) {
    copy_error(error, error_capacity,
               "generated compile append returned an invalid outcome");
    status = BEAGLE_STORE_SERVER_FATAL;
    goto cleanup;
  }
  if (generated_result.field_6) {
    next_generation = generation_create(
        owner, base_generation, generated_result.field_5, error,
        error_capacity);
    if (next_generation == NULL) {
      status = BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
      goto cleanup;
    }
    status = append_log_vector(store, generated_result.field_4, true, error,
                               error_capacity);
    if (status != BEAGLE_STORE_SERVER_OK) {
      store->poisoned = true;
      goto cleanup;
    }
    store->current = next_generation;
    next_generation = NULL;
    generation_release(base_generation);
  }
  status = write_snapshot_vector(store, generated_result.field_7, error,
                                 error_capacity);
  if (status != BEAGLE_STORE_SERVER_OK) {
    goto cleanup;
  }
  result->status = BEAGLE_STORE_SERVER_OK;
  result->found = true;
  result->outcome = (int64_t)generated_result.field_1 == INT64_C(0)
                        ? BEAGLE_STORE_SERVER_COMPILE_APPENDED
                        : BEAGLE_STORE_SERVER_COMPILE_RETAINED;

cleanup:
  if (next_generation != NULL) {
    generation_release(next_generation);
  }
  if (owner != NULL) {
    owner_release(owner);
  }
  if (status != BEAGLE_STORE_SERVER_OK) {
    result->status = status;
  }
  return status;
}

void store_server_compile_value_release(store_server_compile_value *value) {
  void *context;
  store_server_compile_release_fn release;
  uint8_t *allocation;

  if (value == NULL) {
    return;
  }
  context = value->payload.release_context;
  release = value->payload.release;
  allocation = value->payload.data;
  *value = (store_server_compile_value){0};
  if (release != NULL && allocation != NULL) {
    release(context, allocation);
  }
}

int store_server_store_shutdown(store_server_store *store, char *error,
                               size_t error_capacity) {
  store_server_store_shutdown_return generated_result;
  int close_status;
  int status;

  clear_error(error, error_capacity);
  if (store == NULL) {
    copy_error(error, error_capacity,
               "generated store shutdown requires an owned store");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  generated_result = BEAGLE_STORE_SERVER_CALL_STORE_SHUTDOWN(
      &store->current->owner->arena, &store->current->owner->capability,
      store->current->result);
  status = generated_status((int64_t)generated_result.field_0, error,
                            error_capacity,
                            "generated store shutdown failed");
  if (store->poisoned) {
    copy_error(
        error, error_capacity,
        "canonical Store transaction log is poisoned after a durability failure");
    status = BEAGLE_STORE_SERVER_FATAL;
  }
  close_status = store->host.storage_sync(store->host.context, error,
                                          error_capacity);
  if (close_status != BEAGLE_STORE_SERVER_OK) {
    status = close_status;
  }
  close_status = store->host.storage_close(store->host.context, error,
                                           error_capacity);
  if (close_status != BEAGLE_STORE_SERVER_OK) {
    status = close_status;
  }
  if (store->host.snapshot_context != NULL) {
    close_status = store->host.storage_close(store->host.snapshot_context,
                                             error, error_capacity);
    if (close_status != BEAGLE_STORE_SERVER_OK) {
      status = close_status;
    }
  }
  generation_release(store->current);
  free(store->space_id);
  free(store->canonical_log_path);
  free(store);
  return status;
}

int store_server_codec_decode_request(const uint8_t *bytes, size_t length,
                                     store_server_request **request_out,
                                     char *error, size_t error_capacity) {
  store_server_request *request;
  generated_owner *owner;
  native_byte_source *borrowed = NULL;
  uint32_t body_length;
  int status;

  clear_error(error, error_capacity);
  if (request_out == NULL || (bytes == NULL && length != 0u)) {
    copy_error(error, error_capacity,
               "generated request decode requires bytes and an output owner");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  *request_out = NULL;
  if (length < STORE_RPC_PACKET_HEADER_BYTES) {
    copy_error(error, error_capacity,
               "generated request packet ended inside its header");
    return BEAGLE_STORE_SERVER_CLIENT_ERROR;
  }
  body_length = packet_body_length(bytes);
  if (body_length > STORE_RPC_PACKET_MAX_BODY_BYTES) {
    copy_error(error, error_capacity,
               "generated request packet exceeds the body limit");
    return BEAGLE_STORE_SERVER_CLIENT_ERROR;
  }
  if (length != STORE_RPC_PACKET_HEADER_BYTES + (size_t)body_length) {
    copy_error(error, error_capacity,
               length < STORE_RPC_PACKET_HEADER_BYTES + (size_t)body_length
                   ? "generated request packet ended inside its body"
                   : "generated request packet has trailing bytes");
    return BEAGLE_STORE_SERVER_CLIENT_ERROR;
  }
  /* No store is in scope at decode time, so a scratch owner keeps the default
     growth floor even when a store elsewhere derives one from a budget. */
  owner = owner_create(BEAGLE_STORE_SERVER_DEFAULT_ARENA_GROWTH_BYTES, error,
                       error_capacity);
  if (owner == NULL) {
    return BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
  }
  request = malloc(sizeof(*request));
  if (request == NULL) {
    copy_error(error, error_capacity,
               "cannot allocate the generated request wrapper");
    owner_release(owner);
    return BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
  }
  request->owner = owner;
  if (!borrow_bytes(&owner->arena, bytes, length, &borrowed, error,
                    error_capacity)) {
    owner_release(owner);
    free(request);
    return BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
  }
  request->result = BEAGLE_STORE_SERVER_CALL_CODEC_READ_REQUEST(
      &owner->arena, &owner->capability, borrowed);
  status = generated_status((int64_t)request->result.field_0, error,
                            error_capacity,
                            "generated request decode failed");
  if (status != BEAGLE_STORE_SERVER_OK) {
    (void)BEAGLE_STORE_SERVER_CALL_CODEC_RELEASE_REQUEST(
        &owner->arena, &owner->capability, request->result);
    owner_release(owner);
    free(request);
    return BEAGLE_STORE_SERVER_CLIENT_ERROR;
  }
  *request_out = request;
  return BEAGLE_STORE_SERVER_OK;
}

int store_server_codec_encode_response(const store_server_response *response,
                                      uint8_t **bytes_out,
                                      size_t *length_out, char *error,
                                      size_t error_capacity) {
  uint8_t *bytes;

  clear_error(error, error_capacity);
  if (response == NULL || bytes_out == NULL || length_out == NULL) {
    copy_error(error, error_capacity,
               "generated response encode requires owned input and output values");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  *bytes_out = NULL;
  *length_out = 0u;
  /* Dispatch already encoded the packet; its length is at least the packet
     header, so this allocation is never zero-sized. */
  bytes = malloc(response->length);
  if (bytes == NULL) {
    copy_error(error, error_capacity,
               "cannot allocate the encoded response packet");
    return BEAGLE_STORE_SERVER_OUT_OF_MEMORY;
  }
  memcpy(bytes, response->bytes, response->length);
  *bytes_out = bytes;
  *length_out = response->length;
  return BEAGLE_STORE_SERVER_OK;
}

void store_server_codec_release_bytes(uint8_t *bytes) { free(bytes); }

int store_server_codec_read_request(int client_fd,
                                   store_server_request **request_out,
                                   char *error, size_t error_capacity) {
  uint8_t *packet;
  size_t packet_length;
  int status;

  clear_error(error, error_capacity);
  if (request_out == NULL) {
    copy_error(error, error_capacity,
               "generated request read requires an output owner");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  *request_out = NULL;
  status = read_packet(client_fd, &packet, &packet_length, error,
                       error_capacity);
  if (status != BEAGLE_STORE_SERVER_OK) {
    return status;
  }
  status = store_server_codec_decode_request(
      packet, packet_length, request_out, error, error_capacity);
  free(packet);
  return status;
}

int store_server_codec_write_response(
    int client_fd, const store_server_response *response, char *error,
    size_t error_capacity) {
  clear_error(error, error_capacity);
  if (response == NULL) {
    copy_error(error, error_capacity,
               "generated response write requires an owned response");
    return BEAGLE_STORE_SERVER_FATAL;
  }
  return write_bytes(client_fd, response->bytes, response->length, error,
                     error_capacity);
}

void store_server_codec_release_request(store_server_request *request) {
  if (request == NULL) {
    return;
  }
  (void)BEAGLE_STORE_SERVER_CALL_CODEC_RELEASE_REQUEST(
      &request->owner->arena, &request->owner->capability, request->result);
  owner_release(request->owner);
  free(request);
}

void store_server_codec_release_response(
    store_server_response *response) {
  if (response == NULL) {
    return;
  }
  free(response->bytes);
  free(response);
}
